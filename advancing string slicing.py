# Advanced String Slicing:
# How to Effectively Use Negative Numbers in Python Code
#          01234567891234
parrot =  "Norwegian Blue"
print(parrot[0:6]) #Norweg
print(parrot[-14:-8])

#working with negative index
print(parrot[-4:-2])  #Bl
print(parrot[-4:12])  #Bl

print(parrot[-4:])
print(parrot[-14:-5])
